"""Prepare a labelled derivative task from actual DocHopQA source table cells."""
import hashlib
import json
from pathlib import Path
import re
import sys
from bs4 import BeautifulSoup
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / 'code'))
from engineering_oracle import oracle

source = json.loads((HERE.parent / 'singlecase_20261109/table_candidates.json').read_text(encoding='utf-8'))[0]
assert source['pmc'] == 'PMC11835903'
raw = source['context']['Raw content']
soup = BeautifulSoup(raw, 'html.parser')
rows, active = [], False
for tr in soup.select('tbody tr'):
    cells = tr.find_all('td', recursive=False)
    if len(cells) == 1 and cells[0].get('colspan'):
        active = 'System/body location' in cells[0].get_text(' ', strip=True)
        continue
    if not active:
        continue
    assert len(cells) == 3
    label = cells[0].get_text(' ', strip=True)
    weight = int(re.findall(r'\((\d+)\)', label)[-1])
    value = float(re.match(r'\s*([0-9]+(?:\.[0-9]+)?)', cells[1].get_text(' ', strip=True)).group(1))
    rows.append({'row_id': 'R%02d' % (len(rows) + 1), 'label': label, 'value': value,
                 'weight': weight, 'source_row_xml': str(tr)})
assert len(rows) == 12 and sum(r['weight'] for r in rows) == 3020
question = '''Using ONLY the supplied reported subgroup means and counts from Table3,
compute four numerical summaries over the System/body location rows: weighted_mean,
weighted_population_variance of these subgroup means, weighted_population_sd of
these subgroup means, and weighted_geometric_mean. Use n as weight. Specifically,
mu=sum(w*x)/sum(w); variance=sum(w*(x-mu)^2)/sum(w); sd=sqrt(variance);
geometric_mean=exp(sum(w*ln(x))/sum(w)). Round each final result to six decimal
places, without rounding intermediate values. These are arithmetic summaries of
the supplied rounded subgroup means, not a pooled within-study patient variance
or a claim about measurement precision. Ignore the table's within-group SDs,
confidence intervals, comparator rows before System/body location, and p-values.
Return the four requested numeric fields plus evidence_id, an exact nonempty source
quote, and brief limitations. Do not output code or invent a clinical conclusion.'''
payload = {'rows': [{'value': r['value'], 'weight': r['weight']} for r in rows]}
expected = oracle(payload)
x = np.array([r['value'] for r in rows]); w = np.array([r['weight'] for r in rows])
mu = np.average(x, weights=w); variance = np.average((x - mu) ** 2, weights=w)
independent = [mu, variance, np.sqrt(variance), np.exp(np.average(np.log(x), weights=w))]
assert all(abs(expected[k] - v) <= .0000005 for k, v in zip(expected, independent))
out = HERE / 'data'
out.mkdir(exist_ok=True)
(out / 'source_table.xml').write_text(raw, encoding='utf-8')
task = {'task_id': 'engineering_PMC11835903_Tab3_weighted_summaries', 'question': question,
        'payload': payload, 'row_provenance': rows,
        'evidence': [{'evidence_id': 'e1', 'source': 'https://pmc.ncbi.nlm.nih.gov/articles/PMC11835903/#Tab3', 'text': raw}],
        'construction': {'type': 'Researcher-constructed engineering task using real published table data',
            'original_dochop_id': source['id'], 'original_dochop_question': source['original_question'],
            'article_title': 'Evaluating the impact of the Radiomics Quality Score: a systematic review and meta-analysis',
            'doi': '10.1007/s00330-024-11341-y', 'source_table': 'Table3, Radiomics Quality Score subgroup comparison',
            'source_sha256': hashlib.sha256(raw.encode()).hexdigest(),
            'selection': 'All12 rows under System/body location, selected by header before any model execution',
            'manual_intervention': 'Question, formulas, I/O format, source-row selection, tolerances and development admission rules are researcher-defined; candidate code must be generated by Qwen3-Coder-30B.',
            'bioasq_official_result': False}}
(out / 'task.json').write_text(json.dumps(task, ensure_ascii=False, indent=2), encoding='utf-8')
(out / 'oracle.json').write_text(json.dumps({'expected': expected, 'independent_numpy_agrees': True,
    'policy': 'Offline independent evaluator only. Never send to Executor, Manager or Builder.'}, indent=2), encoding='utf-8')
print(json.dumps({'rows': len(rows), 'total_weight': int(sum(w)), 'oracle_crosscheck': True,
                  'source_sha256': task['construction']['source_sha256']}, ensure_ascii=True))
